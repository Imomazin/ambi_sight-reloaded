export default function SidebarNav() {
  const pathname = usePathname();
  const { isSidebarCollapsed, setSidebarCollapsed, currentPersona, currentUser } = useAppState();

  const filteredItems = navItems.filter((item) => {
    if (item.keyUserOnly) return currentUser?.role === 'KeyUser';
    if (item.adminOnly) return currentPersona === 'admin' || currentUser?.role === 'Admin' || currentUser?.role === 'KeyUser';
    return true;
  });

  return (
    <aside
      className={`fixed left-0 top-14 bottom-0 z-40 hidden md:block bg-[var(--sidebar-bg)] backdrop-blur-xl border-r border-[var(--border-color)] transition-all duration-200 ${
        isSidebarCollapsed ? 'w-16' : 'w-56'
      }`}
    >
      <div className="flex flex-col h-full">
        <button
          onClick={() => setSidebarCollapsed(!isSidebarCollapsed)}
          className="absolute -right-3 top-5 w-6 h-6 bg-[var(--bg-secondary)] border border-[var(--border-color)] rounded-full flex items-center justify-center text-[var(--text-muted)] hover:text-[var(--text-primary)] transition-colors z-50"
        >
          <svg className={`w-3 h-3 transition-transform ${isSidebarCollapsed ? 'rotate-180' : ''}`} fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={2}>
            <path strokeLinecap="round" strokeLinejoin="round" d="M15 19l-7-7 7-7" />
          </svg>
        </button>

        <nav className="flex-1 px-2 py-4 space-y-0.5 overflow-y-auto custom-scrollbar">
          {filteredItems.map((item) => {
            const isActive = pathname === item.href;
            return (
              <Link
                key={item.name}
                href={item.href}
                className={`sidebar-link ${isActive ? 'active' : ''}`}
                title={isSidebarCollapsed ? item.name : undefined}
              >
                <span className="flex-shrink-0">{item.icon}</span>
                {!isSidebarCollapsed && <span>{item.name}</span>}
              </Link>
            );
          })}
        </nav>

        {!isSidebarCollapsed && (
          <div className="px-4 py-3 border-t border-[var(--border-color)]">
            <p className="text-[11px] text-[var(--text-muted)]">Lumina S v1.0</p>
          </div>
        )}
      </div>
    </aside>
  );
}
